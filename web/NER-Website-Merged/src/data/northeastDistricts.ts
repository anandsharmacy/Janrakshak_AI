export const NORTHEAST_STATES = Array.from(new Set(NORTHEAST_DISTRICTS.map(d => d.state))).sort();

export function getDistrictsForState(state: string): string[] {
  if (state === 'ALL') {
    return NORTHEAST_DISTRICTS.map(d => d.district).sort();
  }
  return NORTHEAST_DISTRICTS.filter(d => d.state === state).map(d => d.district).sort();
}

