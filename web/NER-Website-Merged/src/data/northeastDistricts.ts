const SORTED_DISTRICTS = [...NORTHEAST_DISTRICTS].sort((a, b) => b.district.length - a.district.length);

export function matchLocationToDistrictAndState(text: string): { district?: string; state?: string } {
  if (!text) return {};
  const lower = text.toLowerCase();

  for (const [town, info] of Object.entries(TOWN_DISTRICT_MAP)) {
    if (lower.includes(town)) {
      return info;
    }
  }

  for (const d of SORTED_DISTRICTS) {
    if (lower.includes(d.district.toLowerCase())) {
      return { district: d.district, state: d.state };
    }
  }

  for (const st of NORTHEAST_STATES) {
    if (lower.includes(st.toLowerCase())) {
      return { state: st };
    }
  }

  return {};
}
