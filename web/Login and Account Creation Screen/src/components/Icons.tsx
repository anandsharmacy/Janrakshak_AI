export function ChakraMark({ size = 24 }: { size?: number }) {
  const spokes = Array.from({ length: 24 }).map((_, i) => {
    const a = (i * 15 * Math.PI) / 180;
    return (
      <line
        key={i}
        x1={12 + 2 * Math.cos(a)}
        y1={12 + 2 * Math.sin(a)}
        x2={12 + 9 * Math.cos(a)}
        y2={12 + 9 * Math.sin(a)}
        stroke="currentColor"
        strokeWidth="0.7"
      />
    );
  });
  return (
    <svg width={size} height={size} viewBox="0 0 24 24" fill="none">
      <circle cx="12" cy="12" r="9.5" stroke="currentColor" strokeWidth="1" />
      <circle cx="12" cy="12" r="2" stroke="currentColor" strokeWidth="1" />
      <circle cx="12" cy="12" r="1" fill="currentColor" />
      {spokes}
    </svg>
  );
}

